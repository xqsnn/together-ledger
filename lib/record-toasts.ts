/** 记住上一条，避免连着两笔弹出同一句话。 */
let previous = '';

export function pickRecordToast(type: 'income' | 'expense') {
  const pool = type === 'income' ? INCOME_TOASTS : EXPENSE_TOASTS;
  const fresh = pool.filter((text) => text !== previous);
  const next = fresh[Math.floor(Math.random() * fresh.length)] ?? pool[0];
  previous = next;
  return next;
}
